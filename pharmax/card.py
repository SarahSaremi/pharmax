"""Generate the public dataset card (data/public/README.md).

Reads ONLY files in the public tier, so the card can never contain restricted information. It is regenerated
by `pharmax pool` and `pharmax dataset-card`, so its numbers always match the published files."""
import csv
import json
import os
from collections import defaultdict


def _rows(path):
    with open(path, encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def _top(cells, lex, role, sensitive, n=10):
    tot = defaultdict(int)
    for r in cells:
        if r['role'] == role and r['drug_id'] not in sensitive:
            tot[r['drug_id']] += int(r['n_senders'])
    return [(lex[d]['name'], lex[d]['category'], v) for d, v in sorted(tot.items(), key=lambda x: -x[1])[:n]]


def build_card(public_root):
    with open(os.path.join(public_root, 'pooled_meta.json'), encoding='utf-8') as f:
        meta = json.load(f)
    summ = _rows(os.path.join(public_root, 'pooled_monthly_summary.csv'))
    cells = _rows(os.path.join(public_root, 'pooled_drug_month_counts.csv'))
    lex = {r['drug_id']: r for r in _rows(os.path.join(public_root, 'lexicon.csv'))}
    flags = meta['sensitive_flags']
    sensitive = {d for d, r in lex.items() if set(r['flags']) & set(flags)}

    tot = lambda col: sum(int(r[col]) for r in summ)
    n_msg, n_txt = tot('n_messages'), tot('n_with_text')
    pct = lambda a, b: f'{100 * a / b:.1f}%' if b else 'n/a'
    reviewed = sum(1 for r in lex.values() if r['review_status'] == 'reviewed')
    multi = sum(1 for r in cells if int(r['n_channels']) > 1)
    L = []
    w = L.append
    w('# Pooled drug supply and demand in Persian-language Telegram groups')
    w('')
    w(f"_Generated by `python -m pharmax dataset-card` from the files in this folder (pooling run {meta['generated_at']}). "
      "Do not edit by hand; edit `pharmax/card.py` instead._")
    w('')
    w('This folder is the **public tier** of the `pharmax` project: counts pooled across several Telegram groups where '
      'pharmacies and individuals offer and request medicines. It contains **no text, no sender identifiers, no channel '
      'names or codes and no per-channel figures**. See [the project README](../../README.md) for the pipeline and '
      '[PRIVACY_AND_ETHICS](../../docs/PRIVACY_AND_ETHICS.md) for how the data were protected.')
    w('')
    w('## At a glance')
    w('')
    w('| | |')
    w('|---|---|')
    w(f"| Channels pooled | {meta['n_channels']} |")
    w(f"| Language | {', '.join(meta['languages'])} |")
    w(f"| Period | {meta['first_month']} to {meta['last_month']} ({len(summ)} months with activity) |")
    w(f"| Messages | {n_msg:,} ({n_txt:,} with text) |")
    w(f"| Distinct senders | {meta.get('n_distinct_named_senders', 'n/a'):,} named accounts, linked across channels by pseudonym "
      "(all deleted accounts count as one sender) |")
    w(f"| Drug groups in lexicon | {len(lex)} ({reviewed} reviewed by a pharmacist) |")
    w(f"| Published drug-month cells | {len(cells):,} of {meta['n_cells_total']:,} "
      f"({meta['n_cells_suppressed']:,} suppressed) |")
    w(f"| Cells that combine several channels | {multi:,} ({pct(multi, len(cells))}) |")
    w(f"| Versions | schema {meta['schema_version']}, rules {', '.join(meta.get('rules_versions', []))}, "
      f"lexicon `{meta['lexicon_sha1']}` |")
    w('')
    w('## Files')
    w('')
    w('| File | Contents |')
    w('|---|---|')
    w('| `pooled_drug_month_counts.csv` | one row per **month x role (supply/demand/mixed/other) x drug group**: distinct senders, '
      'messages, de-duplicated messages, messages that received a reply |')
    w('| `pooled_monthly_summary.csv` | one row per month: message counts by role, image-only messages, deleted-account messages, distinct senders |')
    w('| `lexicon.csv` | the drug groups, categories, flags (see below) and brand/spelling variants used for matching |')
    w('| `pooled_meta.json` | versions, thresholds and counts for this release |')
    w('')
    w('Column definitions: [docs/DATA_STANDARD.md](../../docs/DATA_STANDARD.md). **The primary measure is `n_senders`** '
      '(distinct senders per month), not message counts, because a few accounts re-post the same catalogue thousands of times.')
    w('')
    w('## Thresholds applied')
    w('')
    flagtxt = ', '.join(f'`{f}`' for f in flags)
    if meta['k'] <= 1:
        w('- Ordinary drugs: **no small-cell suppression** (every cell is published).')
    else:
        w(f"- Ordinary drugs: cells with fewer than **{meta['k']}** distinct pooled senders are removed.")
    w(f"- Sensitive drugs (lexicon flags {flagtxt}: controlled/psychotropic, obstetric/abortifacient-related, unlicensed "
      f"sexual enhancers): cells with fewer than **{meta['k_sensitive']}** distinct pooled senders are removed "
      f"({meta['n_cells_suppressed_sensitive']:,} cells). Totals for these drugs are therefore **under-counts**.")
    w('')
    w('## Composition')
    w('')
    sup, dem, mix, oth, job = (tot(c) for c in ('n_supply', 'n_demand', 'n_mixed', 'n_other', 'n_jobs'))
    w(f"- Roles among messages with text: supply {pct(sup, n_txt)}, demand {pct(dem, n_txt)}, ambiguous {pct(mix, n_txt)}, "
      f"other {pct(oth, n_txt)}, job ads {pct(job, n_txt)} (job ads are excluded from drug counts).")
    w(f"- **Media with no text: {pct(tot('n_media_only'), n_msg)} of all messages** (mostly photos). Their content is "
      "invisible to this text-based analysis; photo posts that have a caption are analysed through the caption only.")
    yr = defaultdict(lambda: [0, 0])
    for r in summ:
        yr[r['month'][:4]][0] += int(r['n_deleted_msgs'])
        yr[r['month'][:4]][1] += int(r['n_messages'])
    by_year = {y: 100 * a / b for y, (a, b) in yr.items() if b}
    hi, lo = max(by_year, key=by_year.get), min(by_year, key=by_year.get)
    w(f"- Messages from deleted accounts: {pct(tot('n_deleted_msgs'), n_msg)} overall, from {by_year[hi]:.0f}% in {hi} to "
      f"{by_year[lo]:.0f}% in {lo}. All deleted accounts count as one sender, so distinct-sender counts are under-estimated, "
      "most in the years with the highest share.")
    w(f"- Share of extracted item lines that matched a lexicon drug group: **{pct(meta.get('item_match_rate', 0), 1)}**. "
      "The rest are long-tail drugs, devices and noise.")
    w('')
    w('## Most frequent drug groups (descriptive only)')
    w('')
    w('Sum over months of distinct pooled senders (sender-months), excluding sensitive-flag drugs. Drug groups are the '
      "project's own grouping of brand names, not pharmacist-verified products.")
    w('')
    for role, title in (('supply', 'Offered'), ('demand', 'Requested')):
        w(f'**{title}**')
        w('')
        w('| drug group | category | sender-months |')
        w('|---|---|---|')
        for name, cat, v in _top(cells, lex, role, sensitive):
            w(f'| {name} | {cat} | {v:,} |')
        w('')
    w('## Lexicon flags')
    w('')
    w('`C` controlled/narcotic/psychotropic/stimulant-type, `A` obstetric/abortifacient-related, `R` rare-disease/orphan-type, '
      '`V` COVID-era, `X` unlicensed sexual-enhancement. A flag marks the drug, not intent: e.g. misoprostol is also used for '
      'ulcers and postpartum bleeding.')
    w('')
    w('## Known limitations')
    w('')
    w('- Supply/demand labels come from rules tuned on **one** channel (informal spot check ~90-95%); accuracy on the others has '
      'not yet been measured. Treat role-level results as provisional until the QA described in '
      '[ADDING_A_CHANNEL](../../docs/ADDING_A_CHANNEL.md) is complete.')
    w('- The lexicon is unreviewed; brand-to-drug mapping was done by the project author.')
    w('- Sender linkage across channels uses display names, so two people with the same name merge and one person with several '
      'names splits.')
    w('- A mention is not a transaction, and a Telegram group is not the market. See [METHODOLOGY](../../docs/METHODOLOGY.md).')
    w('')
    w('## Quick start')
    w('')
    w('```python')
    w('import pandas as pd')
    w("cells = pd.read_csv('pooled_drug_month_counts.csv')")
    w("lex = pd.read_csv('lexicon.csv')[['drug_id', 'name', 'category', 'flags']]")
    w("demand = cells[cells.role == 'demand'].merge(lex, on='drug_id')")
    w("demand.groupby([demand.month.str[:4], 'name']).n_senders.sum().unstack(0).fillna(0)  # yearly sender-months")
    w('```')
    w('')
    w('## Licence and citation')
    w('')
    w('**Not yet chosen.** Until a licence is added, all rights are reserved. Citation text will be added with the first release.')
    return '\n'.join(L) + '\n'


def write_card(public_root):
    path = os.path.join(public_root, 'README.md')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(build_card(public_root))
    return path
