"""Persian (fa) language pack: normalisation, supply/demand/jobs rules, item extraction.

A language pack is any module exposing: LANG, normalize(text), classify(text)->(role, rule),
clean_items(text)->list[str]. Add rules_<lang>.py and register it in pipeline.LANGS to support
another language.
"""
import re

LANG = "fa"
RULES_VERSION = "fa-0.1.0"

_AR = str.maketrans({'ك': 'ک', 'ي': 'ی', 'ى': 'ی', 'ۀ': 'ه', 'ة': 'ه', 'أ': 'ا', 'إ': 'ا', 'ؤ': 'و',
                     '‌': ' ', '‏': '', '‎': '', '\xa0': ' ', 'ـ': ''})
_DIG = str.maketrans('۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789')


def normalize(s):
    """Unify Arabic/Persian letter variants and digits, lower-case Latin, drop diacritics."""
    s = s.translate(_AR).translate(_DIG).lower()
    return re.sub(r'[ً-ٰٟ]', '', s)


# ---- role rules (applied to normalised text) ----------------------------------------------
# Phrases that contain a demand word but are really supply boilerplate ("if you need, PM me").
NEUTRAL = re.compile(r'(در ?صورت ?(نیاز|تمایل|نیازمندی)|نیاز ?داشت|نیاز ?داری|نیاز ?بود|نیاز ?باشد|نیاز ?شد|نیاز ?دارند|هر ?نیازی)')
DEM = re.compile(r'(نیازمند|مورد ?نیاز|نیاز ?دار(م|یم)|نیاز ?است|نیاز ?فوری|نیاز ?به|خریدار|می ?خر(م|یم)|میخر(م|یم)|خرید(ار)? ?(میکن|می ?کن)|کسی ?دار(ه|د)|کسی ?موجود|کسی ?هست|جایی ?(هست|دار|موجود)|کجا ?(هست|پیدا|موجود)|دارین\s*\??|دارید\s*\??|داره ?\?|موجود ?(هست|هس|دارید|داری)? ?\?|لازم ?دار(م|یم)|احتیاج|نیازه|تامین ?میکن|میخواه?(م|یم)|می ?خواه?(م|یم)|اگر ?(کسی|دوستان|همکار)|مشتری ?دار(م|یم)|خریدارم|لطفا ?(قیمت|اعلام)|قیمت ?(بدید|بدین|بده)|پیدا ?(نمیشه|نمی ?شه|نکردم)|شرمنده ?(جایی|کسی)|نایاب ?(هست|شده)?\s*\?)')
SUP = re.compile(r'(موجود(ه|ی|م)?(?! ?(هست|هس) ?\?)|فروش|می ?فروش|میفروش|تخفیف|دار(م|یم) ?(?!نیاز)|پی ?وی|pv|اقلام|تعداد ?محدود|ارسال|قیمت|تومان|ریال|زیر ?قیمت|عمده|حراج|تصفیه|تاریخ ?(بلند|کوتاه|نزدیک)|لیست ?(دارو|اقلام|موجودی)|اماده ?(تحویل|ارسال)|وارد ?شد|رسید)')
JOBS = re.compile(r'(استخدام|کاریابی|جویای ?کار|فرصت ?(های)? ?شغلی|medical_?requirement|نیازمندی ?(های)? ?(علوم|پزشک)|پرسنل ?دارو|تکنسین ?دارو|دستیار ?(دندان|داروساز)|مسئول ?فنی|داروساز ?(با|فعال|مسلط)|حقوق ?(توافقی|ثابت)|رزومه|سابقه ?کار|شیفت|پزشک ?عمومی|دندانپزشک|منشی|اجاره ?(داروخانه|مطب)|واگذاری|فروش ?(داروخانه|مطب|ملک)|دعوت ?همکاری|پورسانت|مدیکال ?مارکت|کاراموز|نیروی ?(کار|انسانی)|نفر ?(نیرو|پرسنل|همکار))')
OFFER = re.compile(r'کسی ?(خواست|نیاز ?داشت|لازم ?داشت|مایل|احتیاج ?داشت)')
ASK = re.compile(r'(کسی|دوستان|همکار(ان|ا)?|از ?دوستان).{0,40}(دار(ه|د|ین|ید)|داشت|موجود|هست|سراغ|پیدا)|(موجود(ه|ی)?|دار(ه|ین|ید)|هست) ?[؟?]|میخواستم|می ?خواستم|جایی ?(موجود|دار|هست)|اگر ?(کسی|دوستان|همکار).{0,30}(داشت|دارد|دارین)|داشتید ?[؟?]')
ASK_VETO = re.compile(r'(موجود ?(است|میباشد|می ?باشد|هست ?)(?!\s*[؟?])|فروش|تخفیف)')
NEED_WORD = re.compile(r'(نیازمند|مورد ?نیاز|خریدار|می ?خر)')


def classify(text):
    """Return (role, rule). role in supply|demand|mixed|other|jobs."""
    n = normalize(text)
    if JOBS.search(n):
        return 'jobs', 'jobs_pattern'
    n2 = NEUTRAL.sub(' ', n)
    if OFFER.search(n2):
        return 'supply', 'offer_phrase'
    if ASK.search(n2) and not ASK_VETO.search(n2):
        return 'demand', 'ask_phrase'
    d, s = bool(DEM.search(n2)), bool(SUP.search(n2))
    q = '؟' in text or '?' in text
    if d and not s:
        return 'demand', 'demand_cue_only'
    if s and not d:
        return 'supply', 'supply_cue_only'
    if d and s:
        if NEED_WORD.search(n2) and len(n2) < 400:
            return 'demand', 'mixed_need_word'
        if q and len(n2) < 200:
            return 'demand', 'mixed_question'
        return 'mixed', 'mixed_unresolved'
    if q and len(n2) < 150:
        return 'demand', 'short_question'
    return 'other', 'no_cue'


