STOPWORDS = _STOP | _FORMS
_NOISE = re.compile(r'https?://\S+|@\w+|\b0?9\d{9}\b|\b\d{10,}\b')


def clean_items(text):
    """Split into lines / emoji-separated chunks; keep 1-2 word chunks after removing stop words,
    dosage forms and numbers. Returns a de-duplicated list (order preserved)."""
    t = normalize(_NOISE.sub('\n', text))
    out, seen = [], set()
    for line in re.split(r'[^\w ‌]+|\n+', t):
        words = [w for w in re.sub(r'[_\d]+', ' ', line).split() if w not in STOPWORDS and len(w) > 1]
        if 1 <= len(words) <= 2:
            item = ' '.join(words)
            if 3 <= len(item) <= 24 and item not in seen:
                seen.add(item)
                out.append(item)
    return out
